# tid 兜底范围 (新分区不在表里时用)
TID_FALLBACK_RANGE = [
    (range(260, 270),   "影视"),
]


def tid_to_category(tid, tname=None):
    """
    根据 tid 返回 (一级分类, 子分类名)
    优先查映射表; 找不到时基于范围兜底; 最后用 tname 兜底
    """
    if tid is not None:
        if tid in TID_MAP:
            sub_name, main_name = TID_MAP[tid]
            return main_name, sub_name
        for r, name in TID_FALLBACK_RANGE:
            if tid in r:
                return name, f"未知子分区(tid={tid})"

    # 没找到, 用 tname 当 fallback
    if tname:
        return tname, tname

    return "未分类", ""
