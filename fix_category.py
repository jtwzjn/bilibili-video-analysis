# 一级 tid 兜底映射 (子 tid 不认识时, 至少能根据所属一级分区给个名)
# B 站 view API 也会返回 copyright/parent_tid, 但我们没存, 所以这里硬编码
TID_FALLBACK_RANGE = [
    (range(260, 270),   "影视"),       # 250-260 多是影视新分区
    # 可以根据需要添加更多
]


def fix_video(path):
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception as e:
        return ("error", str(e))

    tid = data.get("tid")
    if tid is None:
        return ("no_tid", None)

    if data.get("category") and data.get("category") != "":
        return ("already_set", data["category"])

    if tid in TID_MAP:
        sub_name, main_name = TID_MAP[tid]
    else:
        # 兜底
        main_name = None
        for r, name in TID_FALLBACK_RANGE:
            if tid in r:
                main_name = name
                sub_name = f"未知子分区(tid={tid})"
                break
        if main_name is None:
            return ("unknown_tid", tid)

    data["category"] = main_name
    data["tname"]    = sub_name
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    return ("fixed", main_name)


def main():
    files = sorted(VIDEOS_DIR.glob("*.json"))
    print(f"扫描 {len(files)} 个 JSON 文件...")

    stats = {"fixed": 0, "already_set": 0, "no_tid": 0, "unknown_tid": 0, "error": 0}
    unknown_tids = {}
    fixed_categories = {}

    for i, f in enumerate(files):
        status, info = fix_video(f)
        stats[status] = stats.get(status, 0) + 1
        if status == "fixed":
            fixed_categories[info] = fixed_categories.get(info, 0) + 1
        elif status == "unknown_tid":
            unknown_tids[info] = unknown_tids.get(info, 0) + 1
        if (i + 1) % 200 == 0:
            print(f"  进度 {i+1}/{len(files)}")

    print("\n=== 统计 ===")
    for k, v in stats.items():
        print(f"  {k}: {v}")

    print("\n=== 修复后的一级分区分布 ===")
    for cat, n in sorted(fixed_categories.items(), key=lambda x: -x[1]):
        print(f"  {cat}: {n}")

    if unknown_tids:
        print("\n=== 仍然未知的 tid ===")
        for tid, n in sorted(unknown_tids.items(), key=lambda x: -x[1]):
            print(f"  tid={tid}: {n} 个视频")


if __name__ == "__main__":
    main()
